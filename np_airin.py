"""3. numpy.arange"""

import numpy as np

# Contoh 1: hanya stop
a = np.arange(10)
print(a)

# Contoh 2: start, stop
b = np.arange(5, 15)
print(b)

# Contoh 3: start, stop, step
c = np.arange(0, 20, 4)
print(c)

# Contoh 4: dengan angka desimal (step float)
d = np.arange(1, 3, 0.5)
print(d)

# Contoh 5: step negatif (mundur)
