print(e)

"""4. numpy.linspace"""

import numpy as np

# Membuat urutan dari 5 hingga 20 dengan 6 elemen
urutan, jarak = np.linspace(5, 20, 6, retstep=True)
print("Urutan:", urutan)
print("Jarak antara elemen:", jarak)

# Membuat urutan bilangan bulat dari 100 hingga 200 dengan 5 elemen
urutan2 = np.linspace(100, 200, 5, dtype=int)
print("Urutan:", urutan2)

#Membuat urutan dengan num=6 tanpa menggunakan endpoint dan dengan menggunakan retstep
a = np.linspace(0, 50, num=6)
b = np.linspace(0, 50, num=6, endpoint=False)
c, step = np.linspace(0, 50, num=6, retstep=True)

print("Urutan a (dengan endpoint):")
print(a)

print("\nUrutan b (tanpa endpoint):")
print(b)

print("\nUrutan c (dengan retstep):")
print(c)

print("\nJarak antara elemen dalam urutan c:")
print(step)

